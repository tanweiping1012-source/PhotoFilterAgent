"""所有可调参数集中在这里，不散落在代码各处。"""
from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path

# 缓存放用户目录，绝不放进仓库 —— 缓存里含照片衍生数据
DEFAULT_CACHE = Path(
    os.environ.get("PHOTOFILTER_CACHE", Path.home() / ".cache" / "photofilter-rank")
)


@dataclass
class RankConfig:
    # --- 输入 ---
    folder: Path
    target: int = 20
    labels: Path | None = None           # 用户标注文件（每行一个文件名 = 我喜欢这张）
    exclude: tuple[str, ...] = ()        # 相对路径前缀，用于排除人工答案子目录

    # --- 预处理 ---
    max_side: int = 1024                 # 送进模型前的最长边。原图 40MP 会把显存打爆
    jpeg_quality: int = 95

    # --- 挑片风格：这一趟想要什么 ---
    #
    # 实测发现：同一个用户，不同旅行，需要的是**相反方向**的指标。
    #
    #     数据集①（开拓小屋线，用户按人脸挑）
    #       A 质量优先（人脸质量↑）  命中 4/20  p=0.032 ✅
    #       B 氛围优先（美学分↓）    命中 0/20
    #
    #     数据集②（道东三湖，用户按氛围挑）
    #       A 质量优先             命中 1/4
    #       B 氛围优先             命中 2/4
    #
    #     两套名单的重叠：0/20 和 4/20 —— 几乎完全不同的两批照片
    #
    # 关键产品判断：**不要求用户先给正样本。** 真实用户只会说
    # 「帮我从这 500 张里挑 20 张」，他还没看过结果，不知道该给什么范例。
    # 但他能回答「这趟你想要拍得清楚好看的，还是有氛围的瞬间」——
    # 这是一句话的事，而且正是 agent 存在的意义：
    # 确定性排序器不可能知道这一趟想要什么，一次对话就能解决。
    #
    # ⚠️ mood 这一档的证据很弱：只有 4 张金标，2/4、p=0.11，不显著。
    #    它是「值得提供的选项」，不是「已验证的能力」。
    style: str = "quality"        # quality（默认）/ mood

    # --- 人脸大小分层（默认关，见下面的完整测量）---
    #
    # 实测偏差：Apple Vision 的人脸质量分在**人脸裁剪区**上算，脸小意味着像素少、
    # 更难评估，分数系统性偏低 ——
    #
    #     大脸组（脸 ≥0.8% 画面）  92 张   脸质量中位 56
    #     小脸组                  217 张   脸质量中位 33     ← 系统性低 23 分
    #
    # 而用户两种都选（20 张金标里 6 张大脸 / 14 张小脸），
    # 所以排序器**系统性漏掉环境人像这一半**：漏掉的 13 张里只有 1 张脸够大，
    # 而命中的 7 张里有 5 张脸够大。
    #
    # 分层（各组内部各算百分位）确实修好了这个偏差 —— 13 张小脸金标全部上升
    # （−12 到 −48 名），中位名次 80 → 61。但它是个**精度/召回权衡**，
    # 跨 5 次 Vision 扫描一致：
    #
    #              K=20 均值   过显著线   K=50 均值   AUC
    #     现状        3.6       3/5        4.8      0.73–0.74
    #     分层        3.2       1/5        9.4      0.77–0.80
    #
    # 平铺排序把少数几张对的挤在最顶端（金标名次 1、9、13、20）；
    # 分层把正确性摊得更均匀，但顶端更少。
    #
    # **产品默认要 20 张，所以默认关。** 要挑 50 张以上就该打开 ——
    # 那时它是压倒性的（9.4 vs 4.8，接近两倍）。
    # ⚠️ 只在一个数据集上测过。
    stratify_by_face_size: bool = False

    # --- 冷启动策略 ---
    #
    # ⚠️ 两个数据集上的指标排名**完全翻转**，没有一个通吃：
    #
    #     指标                  数据集①    数据集②(清洗后)
    #     Apple Vision 人脸质量   0.723        0.571     ← 默认
    #     topiq_nr-face          0.606        0.685
    #     laion_aes              0.583        0.291
    #
    # 两个集给出相反的偏好，两者均值几乎打平（0.647 vs 0.646）。
    # 默认选 vision_face 的唯一理由是**证据强度**：
    # 数据集① 有 20 张金标，数据集② 清洗后只剩 4 张 ——
    # 4 张金标的 AUC 估计极不可靠。
    #
    # ⚠️ 这不是一个有把握的选择。换第三批照片很可能翻车。
    # 见 docs/versions/V4-GENERALIZATION.md。
    cold_strategy: str = "auto"        # auto / face / vision_face / laion_aes / blend
    # ━━ 个人口味探针：默认关闭 ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    #
    # 这是 v4 最初的核心卖点，实测**在交付层面没有收益**：
    #
    #     方案                   交付前20命中      AUC
    #     冷启动（忽略标注）       1.83 ± 0.97     0.714
    #     融合 0.55/0.45         1.57 ± 0.80     0.754
    #     （30 次随机划分，10 张标注，同一组留出金标）
    #
    #     融合胜过冷启动 7/30 次，打平 13 次，落后 10 次
    #
    # AUC 确实更高（+0.04），但**产品交付的是前 20 张，那一项没有改善**。
    # 这和 laion_aes + topiq 那次融合是同一个模式：全局排序变好，头部被稀释。
    #
    # 所以默认关闭。打开它需要显式设 use_probe=True，并且知道自己在做什么。
    # 代码和测量都留着 —— 这个负面结果本身是产出。
    use_probe: bool = False
    # 少于这个数就完全不用探针。实测标 3 张时探针 0.555，冷启动 0.725 —— 差得远。
    min_labels: int = 5
    # 探针在融合里占的权重。**纯探针永远更差**（m=15 时 0.721 vs 冷启动 0.739），
    # 但按 0.4~0.5 的权重融进去，每个标注量上都超过两个纯方案：
    #
    #     探针权重 w     m=5     m=10    m=15
    #     0.0 冷启动    0.721   0.720   0.739
    #     0.4          0.735   0.749   0.789
    #     0.5          0.723   0.748   0.795   ← 最优
    #     1.0 纯探针    0.603   0.666   0.721
    #
    # 这两个信号真互补：vision_face 测「脸拍得好不好」，探针学「这个人喜欢什么内容」。
    # ⚠️ 权重只在这一个数据集上调过，换一批照片要重测。
    probe_weight_min: float = 0.40       # 刚够 min_labels 时
    probe_weight_max: float = 0.50       # 标注充足时的上限
    probe_weight_full_at: int = 15       # 标到这个数就用 max
    # 标注太集中（都来自同一段旅程/同一地点）时，探针学到的是「像那个地方」而不是
    # 「好照片」，结果比不标还差。超过这个集中度就退回冷启动并警告用户。
    # 1.05 是实测分界：分散组平均 AUC 0.647，集中组 0.476。
    max_label_concentration: float = 1.05

    # --- 个人探针 ---
    probe_l2: float = 3.0
    probe_iters: int = 800   # 不是越多越好，见 taste.py 陷阱二
    probe_lr: float = 0.5

    # --- 去重 ---
    # CLIP 余弦没有绝对刻度：同一次旅行里随机两张的中位余弦就有 0.798。
    # 所以阈值取「本批照片自己的余弦分布」的分位数，再套一个下限。
    # 309 张实测：98 分位 → 阈值 0.973 → 128 组、最大组 13 张（合理）
    #             写死 0.86 → 2 组（整批串成一团）
    family_percentile: float = 98.0      # 同场景组
    dup_percentile: float = 99.5         # 近重复
    cosine_floor: float = 0.90           # 分位数再低也不低于此值
    family_cap: int = 2                  # 同一组最多入选几张

    # --- 资格门（本机免费，见 eligibility.py）---
    #
    # 默认**开启**。
    #
    #     数据集①（309张/20金标）：27 张闭眼照里 0 张是金标
    #     数据集②（133张/6金标）： 9 张闭眼照里 2 张是金标
    #
    # 数据集② 那 2 张一度让我把这道门判成有害、改成默认关。
    # 但**用户本人确认那 2 张是他自己挑的时候手滑，不是有意的风格选择** ——
    # 这是只有用户知道的信息，实验数据推不出来。
    #
    # 剔除那 2 张噪声重算：数据集② 的金标从 6 张降到 4 张，
    # vision_face 的 AUC 从 0.455 回到 0.571 —— 确实是标注噪声在拖。
    #
    # 教训不是「资格门有害」，而是**人工答案本身也有噪声**，
    # 而我差点拿这份噪声去推翻一条正确的设计。
    # v3 的 rubric 写「闭眼可能是有意的风格」这个顾虑仍然成立，
    # 所以保留成可关的选项，而不是硬淘汰。
    block_closed_eyes: bool = True
    engine_binary: Path | None = None       # Swift 引擎路径；None 则跳过并如实报告
    engine_workdir: Path | None = None

    # --- 运行 ---
    cache_dir: Path = DEFAULT_CACHE
    device: str = "auto"                 # auto / mps / cuda / cpu

    def resolve_device(self) -> str:
        if self.device != "auto":
            return self.device
        import torch

        if torch.backends.mps.is_available():
            return "mps"
        if torch.cuda.is_available():
            return "cuda"
        return "cpu"
